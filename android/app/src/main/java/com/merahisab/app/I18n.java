    /** Translate a UI string. Text without Gujarati letters is returned untouched. */
    public static String tr(String s) {
        if (s == null || s.length() == 0) return s;
        int i = idx();
        if (i == 0) return s;
        boolean has = false;
        for (int k = 0; k < s.length(); k++) { char c = s.charAt(k); if (c >= 0x0A80 && c <= 0x0AFF) { has = true; break; } }
        if (!has) return s;
        String[] t = M.get(s);
        if (t != null) return t[i - 1];
        for (String k : frag) {
            if (s.indexOf(k) >= 0) {
                String[] v = M.get(k);
                s = s.replace(k, v[i - 1]);
            }
        }
        return s;
    }


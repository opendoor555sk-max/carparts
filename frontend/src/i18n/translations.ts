export type TranslationKey = keyof (typeof dict)["en"];

export function translate(lang: Language, key: TranslationKey): string {
  return dict[lang]?.[key] ?? dict.en[key] ?? key;
}

// For StatusChip and other places that render a raw backend/status string
// (condition, verification status, limit status, etc.) rather than a fixed
// translation key. Unlike translate(), an unmapped value falls back to the
// ORIGINAL string, not the lookup key — status values come from many
// scattered vocabularies across the app, so a value not yet in status.*
// must still display as-is rather than as a raw "status.Xyz" key string.
export function translateStatus(lang: Language, status: string): string {
  const key = `status.${status}`;
  const val = (dict[lang] as Record<string, string>)[key];
  return val ?? status;
}
